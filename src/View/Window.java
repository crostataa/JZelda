package View;

/**
 * Identificatori delle diverse schermate gestite dal {@link LayoutManager} tramite CardLayout.
 */
public enum Window {

    /** Schermata del menu principale. */
    MENU,
    /** Schermata di gioco principale. */
    GIOCO,
    /** Schermata dello shop del mercante. */
    SHOP,
    /** Schermata della classifica e statistiche di carriera. */
    STATISTICHE,
    /** Schermata di Game Over. */
    GAMEOVER,
    /** Schermata finale di vittoria. */
    VITTORIA,
    /** Schermata di selezione dell'avatar/skin. */
    SKIN

}
